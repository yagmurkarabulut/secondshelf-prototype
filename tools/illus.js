// Inlines assets/illustrations/*.svg into index.html (between /* ILLUS:START */ and /* ILLUS:END */).
// Node only, no dependencies: node tools/illus.js   (idempotent: running it twice gives the same file)
const fs = require('fs'); const path = require('path');
const root = path.join(__dirname, '..');
const dir = path.join(root, 'assets/illustrations');
const file = path.join(root, 'index.html');
const START = '/* ILLUS:START */', END = '/* ILLUS:END */';
const names = fs.readdirSync(dir).filter(f => f.endsWith('.svg')).sort();
const entries = names.map(f => {
  let svg = fs.readFileSync(path.join(dir, f), 'utf8')
    .replace(/^\uFEFF/, '')
    .replace(/<\?xml[^>]*\?>\s*/g, '')
    .replace(/<!DOCTYPE[^>]*>\s*/gi, '')
    .trim();
  // safe inside a JS template literal and an inline <script>
  svg = svg.replace(/\\/g, '\\\\').replace(/`/g, '\\`').replace(/\$\{/g, '\\${').replace(/<\/script/gi, '<\\/script');
  return `  '${f.replace(/\.svg$/, '')}': \`${svg}\``;
});
const block = `${START}\n/* Generated by tools/illus.js from assets/illustrations/ — do not edit by hand */\nconst ILLUS = {\n${entries.join(',\n')}\n};\n${END}`;
const html = fs.readFileSync(file, 'utf8');
const a = html.indexOf(START), b = html.indexOf(END);
if (a < 0 || b < a) { console.error(`Markers ${START} … ${END} not found in index.html`); process.exit(1); }
const out = html.slice(0, a) + block + html.slice(b + END.length);
if (out !== html) fs.writeFileSync(file, out);
console.log(`${names.length} illustrations inlined${out === html ? ' (no change)' : ''}`);
